/**
 * 依据案例设计师或标题文本模糊匹配对应的大师传记
 */
export function findMasterForCase(c) {
  if (!c) return null;
  const text = `${c.designer || ""} ${c.title || ""} ${c.intro || ""}`.toLowerCase();
  return MASTERS.find(m => {
    return m.caseKeywords.some(kw => text.includes(kw.toLowerCase()));
  }) || null;
}
